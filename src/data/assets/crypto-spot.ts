import type { Asset } from '@/domain/asset';

const mkSpot = (
  base: string,
  name: string,
  opts: Partial<Asset> = {}
): Asset => ({
  symbol: `${base}USDT`,
  base,
  quote: 'USDT',
  assetClass: 'crypto',
  exchange: opts.exchange || 'binance',
  name,
  currency: 'USDT',
  decimals: opts.decimals ?? 2,
  isTradable: true,
  isListed: true,
  tags: ['spot', 'usdt', ...(opts.tags || [])],
  aliases: [base, `${base}/USDT`, `${base}-USD`, `${base}USD`, ...(opts.aliases || [])],
  ...opts,
});

